"""Disposable Linux CI: real new host, never a production connection or paid API."""
from pathlib import Path
import base64
import hashlib
import json
import os
import secrets
import subprocess
import tempfile
import time
import urllib.request
from deploy import init,init_db

ROOT=Path(__file__).resolve().parents[1]

def main():
    if not hasattr(os,'getuid'):raise RuntimeError('Linux Docker host required')
    with tempfile.TemporaryDirectory(prefix='wiki-host-ci-') as tmp:
        private=Path(tmp)/'private';init(private,'https://ci.example.invalid')
        settings=json.loads((private/'settings.private.json').read_text(encoding='utf-8'))
        random=secrets.token_hex(6);project='wiki-host-ci-'+random;image='wiki-blueprint-ci:'+random
        tokens={role:secrets.token_urlsafe(32) for role in ('reader','proposer','curator','meeting')}
        roles={'reader':'read-only','proposer':'proposal','curator':'curator','meeting':'meeting'}
        registry=[{'id':name,'role':roles[name],'enabled':True,'sha256':hashlib.sha256(('Bearer '+token).encode()).hexdigest(),'tools':['import_meeting'] if name=='meeting' else []} for name,token in tokens.items()]
        state=private/'state';state.mkdir(mode=0o700)
        (state/'ci-tokens.json').write_text(json.dumps(tokens),encoding='utf-8')
        (private/'registry.json').write_text(json.dumps(registry),encoding='utf-8')
        # init_db uses the credentials generated by the existing audited initializer.
        settings['COUCHDB_DATABASE']='wiki_ci_'+random
        (private/'settings.private.json').write_text(json.dumps(settings),encoding='utf-8')
        config={**json.loads((ROOT/'config/host.example.json').read_text(encoding='utf-8')),'profile':'disposable-ci',
                'couchdb':{'url':'http://127.0.0.1:'+settings['COUCHDB_LOCAL_PORT'],'user':settings['LIVESYNC_USER'],'password':settings['LIVESYNC_PASSWORD'],'database':settings['COUCHDB_DATABASE'],'passphrase':settings['COUCHDB_PASSPHRASE']},
                'http':{'bind':'127.0.0.1','port':18788,'public_origin':'https://ci.example.invalid'}}
        (private/'host.json').write_text(json.dumps(config),encoding='utf-8')
        compose=['docker','compose','--project-name',project,'--env-file',str(private/'stack.env'),'-f',str(ROOT/'system/deploy/compose.yaml')]
        def redact(text):
            for value in [*settings.values(),*tokens.values()]:
                if isinstance(value,str) and len(value)>=12:text=text.replace(value,'[REDACTED_CI_VALUE]')
            return text
        def run(args,timeout=600):
            try:
                p=subprocess.run(args,capture_output=True,text=True,timeout=timeout)
            except subprocess.TimeoutExpired as error:
                out=(error.stdout or b'')+(error.stderr or b'')
                if isinstance(out,bytes):out=out.decode('utf-8','replace')
                print(redact(out[-12000:]),flush=True)
                raise RuntimeError('Owned CI operation timed out; see last real checkpoint') from None
            if p.returncode:
                print(redact((p.stdout+p.stderr)[-12000:]),flush=True)
                raise RuntimeError('Owned CI operation failed, exit '+str(p.returncode))
            if p.stdout:print(redact(p.stdout[-12000:]),flush=True)
        try:
            run([*compose,'up','-d','couchdb'])
            url=config['couchdb']['url']+'/_up'
            auth=base64.b64encode((settings['COUCHDB_ADMIN_USER']+':'+settings['COUCHDB_ADMIN_PASSWORD']).encode()).decode()
            for _ in range(60):
                try:
                    with urllib.request.urlopen(urllib.request.Request(url,headers={'Authorization':'Basic '+auth}),timeout=3) as response:
                        if response.status==200:break
                except OSError:pass
                time.sleep(1)
            else:raise RuntimeError('Disposable CouchDB not ready')
            init_db(private)
            run(['docker','build','-f',str(ROOT/'host/Dockerfile'),'-t',image,str(ROOT)])
            run(['docker','run','--rm','--network','host','--user',str(os.getuid())+':'+str(os.getgid()),
                 '-v',str(private)+':/private:rw','-e','WIKI_CONFIG=/private/host.json','--entrypoint','node',image,'/wiki/host/integration.mjs'])
        finally:
            run([*compose,'down','--volumes','--remove-orphans'])
            subprocess.run(['docker','image','rm',image],capture_output=True,timeout=60)

if __name__=='__main__':main()
